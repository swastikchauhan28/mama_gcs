"""Print synthetic fixtures using an already-installed PyMAVLink 2.4.49; never downloads anything."""
import importlib
import importlib.metadata

version = importlib.metadata.version("pymavlink")
if version != "2.4.49":
    raise SystemExit(f"Expected pymavlink 2.4.49, found {version}")
print("# Synthetic fixtures generated by PyMAVLink 2.4.49 common dialect; see docs/phase-109-report.md")
for dialect, label in (("v10", "v1"), ("v20", "v2")):
    module = importlib.import_module(f"pymavlink.dialects.{dialect}.common")
    mav = module.MAVLink(None, srcSystem=42, srcComponent=1)
    mav.seq = 7
    messages = [
        ("heartbeat", mav.heartbeat_encode(10, 3, 0, 4, 4, 3)),
        ("rc_channels", mav.rc_channels_encode(123456, 2, 1500, 1700, *([65535] * 16), 200)),
        ("sys_status", mav.sys_status_encode(7, 3, 1, 675, 24600, 125, 67, 125, 4, 1, 2, 3, 4)),
    ]
    if label == "v2":
        messages += [
            ("rc_zero_rssi", mav.rc_channels_encode(123456, 2, 1500, 1700, *([65535] * 16), 0)),
            ("sys_zero_remaining", mav.sys_status_encode(7, 3, 1, 675, 24600, 125, 0, 125, 4, 1, 2, 3, 4)),
        ]
    for name, message in messages:
        print(f"{label}_{name}={message.pack(mav).hex()}")
