"""Print synthetic multi-source fixtures with PyMAVLink 2.4.49; no downloads."""
import importlib
import importlib.metadata

if importlib.metadata.version("pymavlink") != "2.4.49":
    raise SystemExit("Expected pymavlink 2.4.49")
print("# Synthetic fixtures generated by PyMAVLink 2.4.49 common dialect; see docs/phase-111-report.md")
for dialect, version in (("v10", "v1"), ("v20", "v2")):
    module = importlib.import_module(f"pymavlink.dialects.{dialect}.common")
    for source, system, component in (("other_system", 99, 1), ("other_component", 42, 2)):
        mav = module.MAVLink(None, srcSystem=system, srcComponent=component)
        mav.seq = 7
        messages = (
            ("heartbeat", mav.heartbeat_encode(10, 3, 0, 4, 4, 3)),
            ("rc", mav.rc_channels_encode(123456, 2, 1100, 1900, *([65535] * 16), 100)),
            ("status", mav.sys_status_encode(7, 3, 1, 675, 12000, 125, 30, 125, 4, 1, 2, 3, 4)),
        )
        for name, message in messages:
            print(f"{version}_{source}_{name}={message.pack(mav).hex()}")
