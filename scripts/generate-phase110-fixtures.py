"""Print synthetic RADIO_STATUS fixtures with installed/unpacked PyMAVLink 2.4.49; no downloads."""
import importlib
import importlib.metadata

if importlib.metadata.version("pymavlink") != "2.4.49":
    raise SystemExit("Expected pymavlink 2.4.49")
print("# Synthetic fixtures generated by PyMAVLink 2.4.49 common dialect; see docs/phase-110-report.md")
for dialect, label in (("v10", "v1"), ("v20", "v2")):
    module = importlib.import_module(f"pymavlink.dialects.{dialect}.common")
    mav = module.MAVLink(None, srcSystem=68, srcComponent=68)
    mav.seq = 7
    message = mav.radio_status_encode(95, 100, 80, 4, 5, 17, 23)
    print(f"{label}_radio_status={message.pack(mav).hex()}")
